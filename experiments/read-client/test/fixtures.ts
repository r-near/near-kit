export interface WireRequest {
  jsonrpc: string
  id: string | number
  method: string
  params: Record<string, unknown>
}

export function harness(
  respond: (request: WireRequest, init: RequestInit) => unknown | Response | Promise<unknown | Response> = () => accountWire,
  envelope = true,
) {
  const requests: Array<{ url: string; request: WireRequest; init: RequestInit }> = []
  const fetch: typeof globalThis.fetch = async (input, init = {}) => {
    // The object is generated by the client under test. Assertions inspect it below.
    const request = JSON.parse(String(init.body)) as WireRequest
    requests.push({ url: String(input), request, init })
    const result = await respond(request, init)
    if (result instanceof Response) return result
    return new Response(JSON.stringify(envelope
      ? { jsonrpc: "2.0", id: request.id, result }
      : result), { headers: { "content-type": "application/json" } })
  }
  const provide = <A, E, R>(program: Effect.Effect<A, E, R>) => program.pipe(
    Effect.provide(Near.fetchLayer),
    Effect.provideService(FetchHttpClient.Fetch, fetch),
  )
  return { requests, fetch, provide }
}

